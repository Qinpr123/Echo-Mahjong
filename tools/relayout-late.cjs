const fs = require('fs');
const path = require('path');
const c = require('./relayout-core.cjs');
const ROOT = path.resolve(__dirname, '..', '..');

const STEPS = {
  1: 12, 2: 13, 3: 16, 4: 17, 5: 21, 6: 21, 7: 23, 8: 26,
  9: 29, 10: 31, 11: 34, 12: 34,
  13: 44, 14: 43, 15: 46, 16: 54, 17: 59, 18: 64, 19: 63, 20: 66
};

function checkShape(level, cells) {
  const byZ = {};
  for (const t of cells) (byZ[t.z] = byZ[t.z] || []).push(t);
  const zs = Object.keys(byZ).map(Number).sort((a, b) => a - b);
  for (let i = 1; i < zs.length; i++) {
    if (byZ[zs[i]].length >= byZ[zs[i - 1]].length) {
      throw new Error(`L${level}: layer ${zs[i]} not thinner than ${zs[i - 1]}`);
    }
  }
  for (const z of zs) {
    if (z > 0 && byZ[z].length < 5) throw new Error(`L${level}: micro layer z${z}`);
  }
  const key = (x, y) => x + ',' + y;
  for (let z = 1; z < zs.length; z++) {
    const support = new Set(byZ[z - 1].map(t => key(t.x, t.y)));
    for (const t of byZ[z]) {
      if (!support.has(key(t.x, t.y))) throw new Error(`L${level}: unsupported (${t.x},${t.y},z${z})`);
    }
  }
  const EPS = 1e-6;
  const touching = (a, b) => {
    if (a.z !== b.z) return false;
    const dx = Math.abs(a.x - b.x), dy = Math.abs(a.y - b.y);
    return (dy < EPS && Math.abs(dx - 1) < EPS) || (Math.abs(dy - 1) < EPS && dx <= 0.5 + EPS);
  };
  for (const z of zs.filter(v => v > 0)) {
    const list = byZ[z];
    const seen = new Set();
    let islands = 0;
    for (const start of list) {
      if (seen.has(start.id)) continue;
      islands++;
      const stack = [start];
      seen.add(start.id);
      while (stack.length) {
        const cur = stack.pop();
        for (const n of list) {
          if (!seen.has(n.id) && touching(cur, n)) { seen.add(n.id); stack.push(n); }
        }
      }
    }
    if (islands < 2 || islands > 4) throw new Error(`L${level}: z${z} has ${islands} islands`);
  }
}

function choose(level) {
  const cells = c.makeLayout(level);
  checkShape(level, cells);
  const target = c.TARGETS[level];
  for (let i = 0; i < 4000; i++) {
    const rng = c.mulberry32(level * 100003 + i * 7919);
    const g = c.generatePairs(cells, target, rng, { noTopPair: target.x > 0 });
    if (!g) continue;
    const m = c.metrics(cells, g.pairs, g.F0);
    if (m.freePairs !== target.k) continue;
    if (m.linked < target.l || m.linked > target.lMax) continue;
    if (m.interiorLinked < 1) continue;
    if (m.locked < (target.minLocked ?? 1)) continue;
    if (m.crossFree < target.x) continue;
    const af = c.assignFaces(cells, g.pairs, g.F0, c.EXTRAS[level], rng);
    if (!af) continue;
    const model = c.buildModel(cells, af.faceById);
    const sol = c.allPathsWin(cells, model, level >= 18 ? 2000000 : 900000);
    if (!sol.ok || sol.dead) continue;
    const byId = {};
    for (const t of cells) byId[t.id] = t;
    const links = g.pairs.filter(([a, b]) => g.F0.has(a) && g.F0.has(b) && c.adjacent(byId[a], byId[b]))
      .map(([a, b]) => [byId[a], byId[b]].map(t => `(${t.x},${t.y},z${t.z})`).join('-'));
    return { cells, faces: af.faceById, metrics: m, nodes: sol.nodes, seed: i, links };
  }
  throw new Error('no candidate for L' + level);
}

const picks = {};
for (let level = 13; level <= 20; level++) {
  const p = choose(level);
  picks[level] = p;
  console.log('L' + level, 'seed=' + p.seed, JSON.stringify(p.metrics),
    'nodes=' + p.nodes, 'links=' + p.links.join(' '));
}

const out = c.LEVELS.map(lv => {
  if (lv.level < 13 || lv.level > 20) {
    return { ...lv, steps: STEPS[lv.level] || lv.steps, layout: lv.layout.map(t => ({ ...t })) };
  }
  const p = picks[lv.level];
  const layout = p.cells.map(t => ({ id: t.id, x: t.x, y: t.y, z: t.z, face: p.faces[t.id] }));
  const layers = Math.max(...layout.map(t => t.z)) + 1;
  return {
    ...lv, tiles: layout.length, pairs: layout.length / 2, layers,
    steps: STEPS[lv.level], layout
  };
});

