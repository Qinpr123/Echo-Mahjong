'use strict';
/* Re-pair L8-L10 keeping geometry/steps, so opening linked pairs sit inside the pile
   instead of repeatedly on the outermost middle edge. */
const fs = require('fs');
const path = require('path');
const c = require('./relayout-core.cjs');

const ROOT = path.resolve(__dirname, '..', '..');
const FILE = path.join(ROOT, 'demo/assets/levels.js');
const levels = c.LEVELS;
const byLevel = {};
for (const lv of levels) byLevel[lv.level] = lv;

const SPEC = {
  8: { k: 3, l: 0, x: 1, lMax: 1 },
  9: { k: 3, l: 0, x: 1, lMax: 1 },
  10: { k: 3, l: 0, x: 1, lMax: 1 },
  12: { k: 4, l: 1, x: 1, lMax: 2 }
};

function cellsOf(lv) {
  return lv.layout.map((t, i) => ({ id: i, x: t.x, y: t.y, z: t.z }));
}

for (const n of Object.keys(SPEC)) {
  const lv = byLevel[n];
  const target = SPEC[n];
  const cells = cellsOf(lv);
  const minX = Math.min(...cells.map(t => t.x));
  const maxX = Math.max(...cells.map(t => t.x));
  const minY = Math.min(...cells.map(t => t.y));
  const maxY = Math.max(...cells.map(t => t.y));
  let best = null;
  for (let seed = 1; seed <= 20000 && !best; seed++) {
    const rng = c.mulberry32(seed * 7919 + Number(n));
    const gen = c.generatePairs(cells, target, rng, { noTopPair: true });
    if (!gen) continue;
    const { pairs, F0 } = gen;
    const m = c.metrics(cells, pairs, F0);
    if (m.freePairs !== target.k || m.linked > target.lMax) continue;
    if (m.topPairs !== 0 || m.crossFree < target.x) continue;
    if (m.locked < 1 || m.locked > 12) continue;
    const faces = c.assignFaces(cells, pairs, F0, [], rng);
    if (!faces) continue;
    const model = c.buildModel(cells, faces.faceById);
    const win = c.allPathsWin(cells, model, 400000);
    if (!win.ok) continue;
    best = { seed, pairs, F0, faces, m, win };
  }
  if (!best) { console.error('L' + n + ' no candidate'); process.exit(1); }
  lv.layout = lv.layout.map((t, i) => ({ ...t, face: best.faces.faceById[i] }));
  console.log('L' + n, 'seed=' + best.seed, JSON.stringify(best.m), 'states=' + best.win.states,
    'pairs=' + best.pairs.map(([a, b]) => {
      const A = cells[a], B = cells[b];
      const tag = best.F0.has(a) && best.F0.has(b) ? (c.adjacent(A, B) ? 'LINK' : 'open') : 'locked';
      return tag + '(' + A.x + ',' + A.y + ',' + A.z + ')-(' + B.x + ',' + B.y + ',' + B.z + ')';
    }).join(' '));
  console.log('  faces=', [...new Set(lv.layout.map(t => t.face))].join(','));
}

const header = '/* generated by tools/relayout-late.cjs + tools/repair-early-pairs.cjs; do not edit by hand */\n' +
  '/* v7: L8-L10 small top layers hold no identical pair; the opening pair links a top tile with a lower free tile. Every level has a full elimination order with no non-empty dead states. */\n';
fs.writeFileSync(FILE, header + 'window.FUANG_LEVELS = ' + JSON.stringify(levels) + ';\n');
console.log('written', FILE);
